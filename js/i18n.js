const TEXTOS = { es: ES, en: EN };

/** Devuelve las funciones de texto y formato de un idioma ("es" o "en"). */
export function idioma(codigo = "es") {
  const lang = TEXTOS[codigo] ? codigo : "es";
  const dic = TEXTOS[lang];
  const region = lang === "es" ? "es-ES" : "en-GB";
  const t = (clave, datos = {}) => {
    let base = dic[clave] ?? ES[clave] ?? clave;
    // «singular|plural»: se elige según datos.n
    if (base.includes("|") && datos.n !== undefined) base = base.split("|")[Number(datos.n) === 1 ? 0 : 1];
    return base.replace(/\{(\w+)\}/g, (m, k) => (datos[k] !== undefined && datos[k] !== null ? String(datos[k]) : m));
  };
  const num = (v, decimales = 0) => {
    if (v === null || v === undefined || !Number.isFinite(Number(v))) return "–";
    const texto = new Intl.NumberFormat(region, { minimumFractionDigits: decimales, maximumFractionDigits: decimales, useGrouping: "always" }).format(Number(v));
    return /^-0([.,]0+)?$/.test(texto) ? texto.slice(1) : texto; // nunca «-0»
  };
  const m2 = (v) => `${num(v)} m²`;
  const ha = (v) => `${num(v / 10000, v < 100000 ? 2 : 1)} ha`;
  const area = (v) => (v == null ? "–" : `${m2(v)} (${ha(v)})`);
  const meses = dic.meses.split(" ");
  const mesAno = (iso) => t("fecha.mes_ano", { mes: meses[Number(iso.slice(5, 7)) - 1], ano: iso.slice(0, 4) });
  const dia = (iso) => t("fecha.dia", { dia: Number(iso.slice(8, 10)), mes: meses[Number(iso.slice(5, 7)) - 1], ano: iso.slice(0, 4) });
  return { codigo: lang, t, num, m2, ha, area, mesAno, dia };
}
